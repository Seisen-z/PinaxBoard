/**
 * An uploaded file's metadata (migration `0003_attachments_and_storage.sql`).
 *
 * The bytes live in Supabase Storage at `bucket/storage_path`, where the path
 * always begins with the owner's user id — that prefix is what the storage
 * policies check. `public_url` is set only for objects in a public bucket;
 * a private file is read through a signed URL, which expires and so is never
 * stored.
 */
export type AttachmentRow = {
  id: string;
  note_id: string;
  owner_id: string;
  bucket: string;
  storage_path: string;
  file_name: string;
  mime_type: string;
  file_size: number;
  public_url: string | null;
  created_at: string;
}

