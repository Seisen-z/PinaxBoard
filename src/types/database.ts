/**
 * Database types for the schema in `supabase/migrations/`.
 *
 * Hand-written to match `0001_initial_schema.sql`. Once a Supabase project
 * exists these can be regenerated instead:
 *
 * ```bash
 * npx supabase gen types typescript --project-id <id> > src/types/database.ts
 * ```
 *
 * Keep the two in step. A mismatch here does not fail the build — it fails at
 * runtime, as a query that silently returns nothing.
 */

/** Anything PostgreSQL will accept in a `jsonb` column. */
export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

/**
 * Row shapes are `type` aliases, never interfaces.
 *
 * postgrest-js constrains a schema's rows to `Record<string, unknown>`. An
 * interface has no implicit index signature and so fails that constraint,
 * which makes the whole `Database` type silently non-conforming — and every
 * query then resolves its rows to `never`. This is why `supabase gen types`
 * emits aliases, and why these must stay aliases when regenerated by hand.
 */

/** Columns a table fills in itself: defaults, and trigger-managed timestamps. */
type Generated = "id" | "created_at" | "updated_at";

type TableShape<Row> = {
  Row: Row;
  Insert: Omit<Row, Generated> & Partial<Pick<Row, Generated & keyof Row>>;
  Update: Partial<Row>;
  /**
   * Required by supabase-js's type inference even when empty. Without it the
   * client resolves every selected row to `never`, which shows up as
   * "Property … does not exist on type 'never'" at each query.
   */
  Relationships: [];
}

